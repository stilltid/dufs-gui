//! 可复用的库部分。
//!
//! 目前只有包装不下"属于运行时"的东西 —— 也就是**图标**：
//! 绘制、导出 `.ico`、把图标写进 exe。这样：
//!   - 程序本体（`src/main.rs`）用它画托盘图标；
//!   - 独立的打包工具（`src/bin/icon_tool.rs`）用它生成/嵌入图标。
//!
//! ★ 为什么要把图标工具从 `main()` 里搬出去：
//!   `main()` 里只该留"程序运行时的事"（含必须的提权重入分支）。
//!   导出 `.ico` / 把图标写进 exe 是**打包步骤**，跟运行时无关，
//!   放在 `main()` 里等于每次启动都背着一坨用不到的逻辑。
//!
//! 说明：图标模块没有任何跨模块依赖（只用 std + windows crate），
//! 所以能干净地待在这一层。

